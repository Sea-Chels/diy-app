/** fix = something's wrong, swap = install or replace a part, setup = BIOS, OS and first boot. */
export type GuideKind = 'fix' | 'swap' | 'setup';
export const KIND_LABEL: Record<GuideKind, string> = { fix: 'Troubleshoot', swap: 'Replace', setup: 'Set up' };

/** 1 = no tools / anyone, 2 = a screwdriver and some care, 3 = a free afternoon. */
export type Difficulty = 1 | 2 | 3;
export const DIFFICULTY_LABEL: Record<Difficulty, string> = { 1: 'Easy', 2: 'Moderate', 3: 'Involved' };

export interface Guide {
  id: string;
  title: string;
  /** Hotspots this guide is listed under. First one is the primary. */
  parts: PartId[];
  /** Extra search words for the guide index. */
  aliases: string[];
  kind: GuideKind;
  difficulty: Difficulty;
  /** Rough time range in minutes. */
  minutes: [number, number];
  /** What a shop would charge vs. doing it yourself, as a sentence fragment. */
  savings?: string;
  tools: string[];
  supplies: string[];
  summary: string;
  steps: string[];
  cautions?: string[];
  /** Only shown for these cooling setups. Omit for all. */
  cooling?: Cooling[];
  /** YouTube search words. */
  query: string;
  /** When the parts picker has a part in this category, its name leads the video search. */
  ctx?: Category;
  /** Shown in the quick-fix bar. */
  featured?: boolean;
}

